/** Authoring shorthand for seed products; build.ts expands it into Sanity documents. */
export type ProductDef = {
	model: string;
	name: string;
	category: string;
	subcategory: string;
	kind: 'camera' | 'recorder' | 'switch' | 'access' | 'intercom' | 'bridge' | 'kit';
	series?: 'value' | 'pro' | 'ultra' | 'sentinel' | 'panosight' | 'rugged';
	status?: 'new' | 'active' | 'discontinued';
	release: string;
	render: string;
	angle?: 'a' | 'b' | 'c';
	summary: string;
	highlights: string[];
	mp?: number;
	sensor?: string;
	lens?: [number, number?];
	lensType?: 'fixed' | 'manual-varifocal' | 'motorized-varifocal' | 'multi-lens';
	zoom?: number;
	light?: 'ir' | 'white' | 'hybrid' | 'none';
	lightRange?: number;
	ip?: 'IP54' | 'IP66' | 'IP67' | 'IP68';
	ik?: 'IK08' | 'IK10';
	poe?: boolean;
	audio?: ('mic' | 'dual-mic' | 'speaker' | 'two-way')[];
	deterrence?: ('audio-alarm' | 'white-strobe' | 'red-blue-strobe')[];
	power?: ('poe' | 'dc12' | 'ac24' | 'solar' | 'cellular')[];
	channels?: number;
	storage?: string;
	temp?: string;
	form?: string;
	tech?: string[];
	ai?: string[];
	cardSpecs?: { label: string; value: string; unit?: string }[];
	variants?: { suffix: string; lensMm?: number; status?: 'new' | 'active' | 'discontinued' }[];
	bundle?: { model: string; quantity: number }[];
	spin?: string;
	solutions?: string[];
};
